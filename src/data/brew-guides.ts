/**
 * Static brewing guide content — methods + step-by-step recipes.
 *
 * Lives in code today (alongside `data/products.ts`) so the structure stays
 * obvious and reviewable. When CMS lands, this whole module becomes a
 * Sanity fetch returning the same `BrewGuide[]` shape — call sites don't
 * change.
 *
 * Each guide is keyed by a URL-safe slug. The slugs are deliberately
 * stable English ones (`v60`, `aeropress`) so we get clean URLs and can
 * later add multilingual title/body fields without breaking links.
 */

