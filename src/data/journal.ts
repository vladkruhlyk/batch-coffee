export function getJournalPost(slug: string): JournalPost | null {
  return JOURNAL_POSTS.find((p) => p.slug === slug) ?? null;
}

export function getRelatedPosts(slug: string, max = 2): JournalPost[] {
  const post = getJournalPost(slug);
  if (!post?.related?.length) {
    return JOURNAL_POSTS.filter((p) => p.slug !== slug).slice(0, max);
  }
  return post.related
    .map((s) => getJournalPost(s))
    .filter((p): p is JournalPost => p !== null)
    .slice(0, max);
}
